test('malicious shared content renders as text, cancellation and stale result handling', async ({ page }) => {
  const schema = { type: 'object', required: ['<img src=x onerror="window.__xss=1">'], additionalProperties: false };
  const hash = LZString.compressToEncodedURIComponent(JSON.stringify({ v: 1, t: 'json-schema-validator', a: 'validate', d: { schema: JSON.stringify(schema), json: '{}', dialect: 'auto', profile: 'standard', formats: false, references: [] } }));
  await page.goto(`/json-schema-validator/#lz:${hash}`);
  await expect(page.locator('#doctor-findings')).toContainText('<img');
  expect(await page.evaluate(() => (window as any).__xss)).toBeUndefined();
  await page.locator('#doctor-auto').uncheck();
  await page.locator('#doctor-json').fill('{"new":1}');
  await expect(page.locator('#doctor-export')).toBeDisabled();
  await expect(page.locator('#doctor-findings')).toBeEmpty();
  await page.locator('#doctor-schema').fill('{"type":"string","pattern":"^(a+)+$"}');
  await page.locator('#doctor-json').fill(JSON.stringify('a'.repeat(80) + '!'));
  await page.locator('#doctor-run').click(); await page.locator('#doctor-cancel').click();
  await expect(page.locator('#doctor-status')).toContainText('cancelled');
});
