test('format safely, scroll a long schema to its last line, and keep heavy code deferred', async ({ page }) => {
  const workerRequests: string[] = [];
  page.on('request', r => { if (r.url().includes('schema-doctor.worker')) workerRequests.push(r.url()); });
  await page.goto('/json-schema-validator/');
  expect(workerRequests).toEqual([]);
  await page.locator('#doctor-auto').uncheck();
  await page.locator('#doctor-schema').fill('{"type":"object","type":"string"}');
  await page.locator('#doctor-format-schema').click();
  await expect(page.locator('#doctor-notice')).toContainText('Duplicate');
  await expect(page.locator('#doctor-schema')).toHaveValue('{"type":"object","type":"string"}');
  const longSchema = { type: 'object', properties: Object.fromEntries(Array.from({ length: 150 }, (_, i) => [`field${i}`, { type: 'string' }])) };
  await page.locator('#doctor-schema').fill(JSON.stringify(longSchema));
  await page.locator('#doctor-format-schema').click();
  await expect(page.locator('#doctor-schema')).toHaveValue(JSON.stringify(longSchema, null, 2));
  await page.locator('#doctor-schema').evaluate((input: HTMLTextAreaElement) => { input.scrollTop = input.scrollHeight; input.dispatchEvent(new Event('scroll')); });
  const bounds = await page.locator('#doctor-schema').evaluate((input: HTMLTextAreaElement) => ({ top: input.scrollTop, height: input.clientHeight, total: input.scrollHeight, transform: (input.parentElement!.querySelector('[data-json-editor-code]') as HTMLElement).style.transform }));
  expect(bounds.top + bounds.height).toBeGreaterThanOrEqual(bounds.total - 2);
  expect(bounds.transform).toContain(`${-bounds.top}px`);
});
